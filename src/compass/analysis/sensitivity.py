"""Variance-based sensitivity analysis (blueprint 16.4, Task 12).

Two hard constraints from the blueprint are enforced here.

1. **Sobol indices are computed on the UNCONDITIONED ensemble only.**  Saltelli
   estimators assume the inputs are drawn independently from the stated prior.
   After phenotype filtering that assumption is destroyed, so applying the same
   estimator to an accepted ensemble would produce numbers with no defined
   meaning (blueprint 16.4, risk table 23).  :func:`sobol_indices` therefore
   refuses to run on a filtered design.
2. **Convergence is reported, not assumed.**  Indices are recomputed on nested
   sub-samples so the reader can see whether they have stabilised.

The Saltelli design itself is generated by SALib; the estimator is cross-checked
against SALib's own implementation in the numerical test-suite.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

__all__ = ["SobolResult", "saltelli_design", "sobol_convergence", "sobol_indices"]


def saltelli_design(n_params: int, n_base: int, seed: int = 0,
                    calc_second_order: bool = True) -> np.ndarray:
    """Saltelli sample in the unit hypercube, shape ``(N*(2D+2), D)``.

    ``n_base`` should be a power of two so the underlying Sobol sequence keeps
    its balance properties.
    """
    from SALib.sample import sobol as sobol_sample

    problem = {
        "num_vars": n_params,
        "names": [f"x{i}" for i in range(n_params)],
        "bounds": [[0.0, 1.0]] * n_params,
    }
    return sobol_sample.sample(problem, n_base, calc_second_order=calc_second_order,
                               seed=seed, scramble=True)


@dataclass
class SobolResult:
    names: list[str]
    S1: np.ndarray
    S1_conf: np.ndarray
    ST: np.ndarray
    ST_conf: np.ndarray
    S2: np.ndarray | None
    S2_conf: np.ndarray | None
    n_base: int
    n_valid: int
    output_name: str

    @property
    def interaction_fraction(self) -> float:
        """``1 - sum(S1)``: the share of output variance carried by interactions.

        This is the single most relevant Sobol summary for COMPASS: it is the
        *functional* counterpart of statistical synergy, and blueprint 16.5
        requires functional claims to rest on quantities like this rather than
        on O-information.
        """
        return float(1.0 - np.nansum(self.S1))

    @property
    def mean_total_minus_first(self) -> float:
        return float(np.nanmean(self.ST - self.S1))

    def as_dict(self) -> dict:
        return {
            "output": self.output_name,
            "n_base": self.n_base,
            "n_valid": self.n_valid,
            "interaction_fraction": self.interaction_fraction,
            "mean_ST_minus_S1": self.mean_total_minus_first,
            "S1": {n: float(v) for n, v in zip(self.names, self.S1, strict=True)},
            "ST": {n: float(v) for n, v in zip(self.names, self.ST, strict=True)},
        }


# Refuse to estimate at all below this fraction of finite outputs.
MIN_VALID_FRACTION = 0.5
# Quote an index quantitatively only at or above this fraction (see warning in
# `sobol_indices`).  Analyses below it are still reported, marked `imputed`.
VALID_FRACTION_FLOOR = 0.90

# Completeness is NECESSARY BUT NOT SUFFICIENT (2026-08-06 audit, M8).
# `quotable` used to mean `valid_fraction >= 0.90` alone, so an index whose
# bootstrap confidence half-width exceeded the estimate itself still counted as
# quotable, and two "quotable" interaction fractions were negative.  A
# quantitatively quotable analysis must additionally be PRECISE -- the widest
# S1 confidence half-width no larger than this multiple of the largest index it
# describes -- and PHYSICALLY PLAUSIBLE.  SALib reports bootstrap confidence
# intervals precisely so that they can gate quotability; see
# https://salib.readthedocs.io/en/latest/api/SALib.analyze.html
CONF_WIDTH_CEILING = 0.5


def sobol_indices(y: np.ndarray, names: list[str], n_base: int,
                  calc_second_order: bool = True, output_name: str = "y",
                  n_bootstrap: int = 100, seed: int = 0) -> SobolResult:
    """First-, total- and second-order Sobol indices from a Saltelli design.

    NaN outputs (samples where the feature is undefined, e.g. spike width for a
    silent cell) are mean-imputed *within the estimator only*, and ``n_valid`` is
    reported so a heavily-imputed index can be discounted.

    .. warning::
       This missingness is **not** missing-at-random: a feature is undefined
       precisely when the sample failed to produce the phenotype, which is a
       deterministic function of the parameters the design is varying.  Filling
       those cells with a constant removes real main-effect structure while
       leaving the variance decomposition to run, which biases
       ``1 - sum(S1)`` *upward*.  Empirically the effect is large: in this
       project the feature with the lowest valid fraction (spike-frequency
       adaptation, 0.53) also carries by far the highest apparent interaction
       fraction (0.99), while the three features that are defined for every
       sample (resting potential, input resistance, mean firing rate) sit near
       0.41.  Only analyses with ``valid_fraction >= VALID_FRACTION_FLOOR``
       should be quoted quantitatively.
    """
    from SALib.analyze import sobol as sobol_analyze

    y = np.asarray(y, dtype=float)
    d = len(names)
    expected = n_base * (2 * d + 2) if calc_second_order else n_base * (d + 2)
    if y.size != expected:
        raise ValueError(
            f"expected {expected} outputs for D={d}, N={n_base} "
            f"(calc_second_order={calc_second_order}), got {y.size}. "
            "Sobol indices require the intact Saltelli design -- a filtered "
            "ensemble is not a valid input (blueprint 16.4)."
        )
    valid = np.isfinite(y)
    if valid.sum() < MIN_VALID_FRACTION * y.size:
        raise ValueError(
            f"only {valid.sum()}/{y.size} outputs are finite for {output_name!r}; "
            "refusing to report Sobol indices for a mostly-undefined feature"
        )
    yy = np.where(valid, y, np.nanmean(y[valid]))

    problem = {"num_vars": d, "names": names, "bounds": [[0.0, 1.0]] * d}
    res = sobol_analyze.analyze(problem, yy, calc_second_order=calc_second_order,
                                num_resamples=n_bootstrap, seed=seed,
                                print_to_console=False)
    return SobolResult(
        names=list(names),
        S1=np.asarray(res["S1"]), S1_conf=np.asarray(res["S1_conf"]),
        ST=np.asarray(res["ST"]), ST_conf=np.asarray(res["ST_conf"]),
        S2=np.asarray(res["S2"]) if calc_second_order else None,
        S2_conf=np.asarray(res["S2_conf"]) if calc_second_order else None,
        n_base=n_base, n_valid=int(valid.sum()), output_name=output_name,
    )


def sobol_convergence(y: np.ndarray, names: list[str], n_base: int,
                      output_name: str = "y", seed: int = 0) -> list[dict]:
    """Recompute indices on nested halves of the base sample (blueprint 16.4).

    Returns one record per base size so the report can show whether the indices
    have converged rather than asserting that they have.
    """
    out = []
    d = len(names)
    n = n_base
    while n >= 16:
        take = n * (2 * d + 2)
        try:
            r = sobol_indices(y[:take], names, n, calc_second_order=True,
                              output_name=output_name, n_bootstrap=50, seed=seed)
            out.append({"n_base": n, "interaction_fraction": r.interaction_fraction,
                        "mean_ST_minus_S1": r.mean_total_minus_first,
                        "max_S1_conf": float(np.nanmax(r.S1_conf)),
                        "max_ST_conf": float(np.nanmax(r.ST_conf))})
        except Exception as exc:  # noqa: BLE001
            out.append({"n_base": n, "error": str(exc)[:120]})
        n //= 2
    return list(reversed(out))
